def _skill(tmp_path: Path) -> Path:
    skill = tmp_path / "SKILL.md"
    skill.write_text("# skill\n")
    return skill


def test_discover_resources_finds_references_and_scripts(tmp_path: Path):
    skill = _skill(tmp_path)
    notes = tmp_path / "references" / "notes.md"
    script = tmp_path / "scripts" / "run.sh"
    skipped = tmp_path / "references" / ".calcifier" / "should_be_skipped.md"
    notes.parent.mkdir()
    script.parent.mkdir()
    skipped.parent.mkdir()
    notes.write_text("notes\n")
    script.write_text("run\n")
    skipped.write_text("skip\n")

    entries = discover_resources(skill)

    assert [entry.path for entry in entries] == ["references/notes.md", "scripts/run.sh"]
    assert all(entry.sha256 for entry in entries)
    assert [entry.size for entry in entries] == [notes.stat().st_size, script.stat().st_size]


