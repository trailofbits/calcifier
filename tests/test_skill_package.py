def test_implicit_resources_ignore_bytecode_but_pin_source(tmp_path: Path):
    skill = _skill(tmp_path)
    scripts = tmp_path / "scripts"
    cache = scripts / "__pycache__"
    cache.mkdir(parents=True)
    source = scripts / "helper.py"
    source.write_bytes(b"print('original')\n")
    before = discover_resources(skill)
    for path in (cache / "helper.cpython-314.pyc", scripts / "helper.pyc", scripts / "helper.pyo"):
        path.write_bytes(b"generated bytecode")
    (cache / "metadata.json").write_bytes(b"{}\n")
    assert discover_resources(skill) == before
    source.write_bytes(b"print('changed')\n")
    assert discover_resources(skill) != before


