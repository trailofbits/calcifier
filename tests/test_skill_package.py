@pytest.mark.parametrize("newline", [b"\n", b"\r\n"])
def test_declared_sibling_data_reaches_a_real_packaged_helper(tmp_path, newline):
    from calcifier import run_command, step

    skill = tmp_path / "SKILL.md"
    skill.write_bytes(
        b"# Skill"
        + newline
        + b"Run {baseDir}/scripts/read.py with {baseDir}/lookup-data/."
        + newline
    )
    helper = tmp_path / "scripts" / "read.py"
    helper.parent.mkdir()
    helper.write_bytes(
        b"from pathlib import Path\nimport json\n"
        b"path = Path(__file__).parent.parent / 'lookup-data' / 'entry.json'\n"
        b"value = path.read_text(encoding='utf-8')\n"
        b"print(json.dumps(json.loads(value)))\n"
    )
    data = tmp_path / "lookup-data" / "entry.json"
    data.parent.mkdir()
    original = json.dumps({"label": "Résumé 雪"}, ensure_ascii=False).encode() + newline
    data.write_bytes(original)
    resources = discover_resources(skill)

    @step
    def run_helper() -> str:
        command = run_command(
            [sys.executable, str(resource("scripts/read.py"))], timeout_seconds=10, mutating=False
        )
        assert command.exit_code == 0, command.stderr
        return command.stdout

    packaged = Recipe(
        fn=lambda: run_helper(),
        name="sibling-data",
        version="0.1",
        skill_root=tmp_path,
        resources=tuple((entry.path, entry.sha256, entry.source) for entry in resources),
    )
    result = packaged.run()

    assert result.ok, result.error
    assert isinstance(result.output, str)
    assert json.loads(result.output) == {"label": "Résumé 雪"}
    assert data.read_bytes() == original


